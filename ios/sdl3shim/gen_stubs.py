#!/usr/bin/env python3
"""Writes sdl3stubs.c: a weak, do-nothing definition for every SDL3 function LWJGL 3.4's SDL binding looks up
(sdl_functions.txt, taken from lwjgl-sdl-3.4.3.jar). The functions sdl3shim.c really implements override these.
A stub returns 0 (false / NULL), which no caller in Minecraft depends on."""
import os, sys
here = os.path.dirname(os.path.abspath(__file__))
names = [l.strip() for l in open(os.path.join(here, "sdl_functions.txt")) if l.strip()]
out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "sdl3stubs.c")
with open(out, "w") as f:
    f.write("/* generated by gen_stubs.py */\n#include <stdio.h>\n#include <stdlib.h>\n")
    f.write("static void qm_stub(const char *n) { if (getenv(\"QM_SDL_TRACE\")) fprintf(stderr, \"SDL shim: stub %s\\n\", n); }\n")
    for n in names:
        f.write('__attribute__((weak, visibility("default"))) void *%s(void) { qm_stub("%s"); return 0; }\n' % (n, n))
print("wrote %d stubs to %s" % (len(names), out))
